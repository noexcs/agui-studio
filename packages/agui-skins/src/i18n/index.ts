const dicts: Record<Lang, Dict> = { en, zh };
let current: Lang = "en";
let overrides: Record<string, string> | null = null;

/** The active dictionary for a language (used by SkinHostProvider). */
export function getDict(lang: Lang): Dict {
  return dicts[lang];
}

/** Shallow per-host overrides; null restores the bundled dictionaries. */
export function setOverrides(next: Record<string, string> | null) {
  overrides = next;
}

export function setLang(lang: Lang) {
  current = lang === "zh" ? "zh" : "en";
}

export function getLang(): Lang {
  return current;
}

export function t(key: keyof Dict): string {
  return overrides?.[key] ?? dicts[current][key] ?? en[key] ?? String(key);
}

export const isZh = () => current === "zh";
